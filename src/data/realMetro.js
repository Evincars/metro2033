import { parseFrontmatter } from '../utils/frontmatter'

const files = import.meta.glob('../content/real-metro/*.md', {
  query: '?raw',
  import: 'default',
  eager: true,
})

export const realMetroStations = Object.values(files)
  .map((raw) => {
    const { meta, body } = parseFrontmatter(raw)
    return {
      id: meta.id,
      title: meta.title ?? meta.id,
      line: Number(meta.line ?? 0),
      lineName: meta.lineName || '',
      lineNameEn: meta.lineNameEn || '',
      opened: meta.opened || '',
      architects: meta.architects || '',
      image: meta.image || '',
      gallery: meta.gallery ? meta.gallery.split('|').filter(Boolean) : [],
      source: meta.source || '',
      body,
    }
  })
  .filter((s) => s.id)
  .sort((a, b) => a.line - b.line || a.title.localeCompare(b.title, 'ru'))

export const realMetroById = Object.fromEntries(realMetroStations.map((s) => [s.id, s]))

